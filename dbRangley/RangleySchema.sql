-- =====================================================================
-- RANGLEY Friends Tables
-- =====================================================================
-- Purpose: Contains logic for friendships inside of rangley
-- Features: TODO currently missing ability to block users
-- tb_friend_requests
-- tb_friendships
-- =====================================================================
CREATE TABLE rangley.tb_friend_requests
(
     friend_request_id          INT8        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
    ,requester_user_id          INT8        NOT NULL  -- Person sending the request
    ,recipient_user_id          INT8        NOT NULL  -- Person receiving the request
    ,friend_request_status_id   INT2        NOT NULL DEFAULT 1
    ,dttm_created_utc          TIMESTAMPTZ  NOT NULL DEFAULT now()
    ,dttm_responded_utc        TIMESTAMPTZ  NULL      -- When accepted/declined
    ,dttm_modified_utc         TIMESTAMPTZ  NULL
    
    -- Can't friend yourself
    ,CONSTRAINT chk_no_self_friend 
        CHECK (requester_user_id != recipient_user_id)
    
    -- Only one active request between two users at a time
    ,UNIQUE (requester_user_id, recipient_user_id)
);

-- Find all requests I sent
CREATE INDEX idx_friend_req_requester 
    ON rangley.tb_friend_requests (requester_user_id, friend_request_status_id);

-- Find all requests sent to me
CREATE INDEX idx_friend_req_recipient 
    ON rangley.tb_friend_requests (recipient_user_id, friend_request_status_id);

-- Find pending requests between two users
CREATE INDEX idx_friend_req_both_users 
    ON rangley.tb_friend_requests (requester_user_id, recipient_user_id, friend_request_status_id);


CREATE TABLE rangley.tb_friendships
(
     friendship_id      INT8        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
    ,user_id_a          INT8        NOT NULL  -- Lower user_id (normalized)
    ,user_id_b          INT8        NOT NULL  -- Higher user_id (normalized)
    ,dttm_created_utc  TIMESTAMPTZ NOT NULL DEFAULT now()
    
    -- Ensure user_id_a < user_id_b (prevents duplicate rows)
    ,CONSTRAINT chk_user_order CHECK (user_id_a < user_id_b)
    
    -- Only one friendship between two users
    ,UNIQUE (user_id_a, user_id_b)
);

-- Find all friends for a user (either side of the relationship)
CREATE INDEX idx_friendship_user_a ON rangley.tb_friendships (user_id_a);
CREATE INDEX idx_friendship_user_b ON rangley.tb_friendships (user_id_b);

